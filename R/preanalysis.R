#' End-to-end preprocessing pipeline for multiple single-cell RNA-seq samples
#'
#' @description
#' This function implements a complete preprocessing workflow for multiple
#' single-cell RNA-seq samples organized in subdirectories. The pipeline includes:
#' \enumerate{
#'   \item ambient RNA contamination correction using \pkg{SoupX},
#'   \item generation of corrected 10X-formatted count matrices,
#'   \item construction of \code{Seurat} objects for each sample,
#'   \item batch quality control, clustering, and doublet removal.
#' }
#'
#' The function is designed for large-scale analyses and processes samples
#' sequentially to minimize memory usage.
#'
#' @param base.dir Character. Base directory containing one subdirectory per sample.
#'   Each sample directory must contain an \code{outs/} folder generated by Cell Ranger.
#' @param mt.genes Character vector of mitochondrial gene names. Required only
#'   when \code{species = "other"}.
#' @param species Character. Species type used to determine how mitochondrial
#'   genes are defined. One of \code{"human"}, \code{"mouse"}, or \code{"other"}.
#' @param pattern_prefix Character. Prefix used when creating Seurat object names
#'   in the target environment.
#' @param out_subdir Character. Name of the subdirectory used to store SoupX-corrected
#'   10X output under each sample's \code{outs/} directory.
#' @param min.cells Minimum number of cells in which a gene must be detected
#'   when creating Seurat objects.
#' @param min.features Minimum number of detected features per cell.
#' @param dims_use Integer vector specifying PCA dimensions to use for initial clustering.
#' @param resolution Resolution parameter for graph-based clustering.
#' @param sct Logical. Whether SCTransform normalization was used upstream
#'   (passed to downstream QC and doublet detection).
#' @param verbose Logical. Whether to print progress messages.
#' @param envir Environment into which Seurat objects will be assigned.
#' @param ... Additional arguments passed to \code{ProcessOneSeurat()} via
#'   \code{BatchProcessSeurat_InPlace()}.
#'
#' @return
#' An invisible list containing:
#' \itemize{
#'   \item \code{sample.names}: detected sample directory names;
#'   \item \code{created_objs}: names of generated Seurat objects;
#'   \item \code{base.dir}: base directory used;
#'   \item \code{out_subdir}: SoupX output subdirectory name;
#'   \item \code{species}: species mode used for mitochondrial gene detection.
#' }
#'
#' @details
#' For \code{species = "human"}, mitochondrial content is calculated using the
#' \code{"^MT-"} gene prefix. For \code{species = "mouse"}, mitochondrial genes
#' are loaded automatically from the \pkg{SingleViral} package. Only when
#' \code{species = "other"} must users supply \code{mt.genes} manually.
#'
#' @seealso
#' \code{\link{ProcessOneSeurat}},
#' \code{\link{BatchProcessSeurat_InPlace}},
#' \code{\link[SoupX]{autoEstCont}}
#'
#' @importFrom DropletUtils write10xCounts
#' @importFrom Seurat Read10X CreateSeuratObject
#'
#' @export
preanalysis <- function(
    base.dir,
    mt.genes = NULL,
    species = c("human", "mouse", "other"),
    pattern_prefix = "data_",
    out_subdir = "Ad3_soupx",
    min.cells = 3,
    min.features = 200,
    dims_use = 1:20,
    resolution = 0.5,
    sct = TRUE,
    verbose = TRUE,
    envir = .GlobalEnv,
    ...
) {
  species <- match.arg(species)
  
  if (!dir.exists(base.dir)) stop("base.dir not found: ", base.dir)
  
  if (species == "other") {
    if (is.null(mt.genes) || length(mt.genes) == 0) {
      stop("For species = 'other', you must provide 'mt.genes'.")
    }
  }
  
  sample.names <- list.dirs(base.dir, full.names = FALSE, recursive = FALSE)
  sample.names <- sample.names[!sample.names %in% c("", ".", "..")]
  if (length(sample.names) == 0) stop("No sample folders found under: ", base.dir)
  
  if (!requireNamespace("Seurat", quietly = TRUE)) stop("Seurat not installed.")
  if (!requireNamespace("DropletUtils", quietly = TRUE)) stop("DropletUtils not installed.")
  if (!exists("load10X", mode = "function")) stop("load10X() not found. Please load SoupX (library(SoupX)).")
  if (!exists("autoEstCont", mode = "function")) stop("autoEstCont() not found. Please load SoupX (library(SoupX)).")
  if (!exists("adjustCounts", mode = "function")) stop("adjustCounts() not found. Please load SoupX (library(SoupX)).")
  if (!exists("setClusters", mode = "function")) stop("setClusters() not found. Please load SoupX (library(SoupX)).")
  if (!exists("BatchProcessSeurat_InPlace", mode = "function")) stop("BatchProcessSeurat_InPlace() not found.")
  if (!exists("ProcessOneSeurat", mode = "function")) stop("ProcessOneSeurat() not found.")
  
  # ---------- 1) SoupX correction + write 10X ----------
  if (verbose) message("== Step 1/3: SoupX correction and write 10X outputs ==")
  
  for (sid in sample.names) {
    data.dir <- file.path(base.dir, sid, "outs")
    if (verbose) message("Processing (SoupX): ", sid, " | ", data.dir)
    
    if (!dir.exists(data.dir)) {
      warning("Missing directory: ", data.dir, " (skip ", sid, ")")
      next
    }
    
    sc <- load10X(data.dir)
    
    tmp <- Seurat::CreateSeuratObject(counts = sc$toc)
    tmp <- Seurat::NormalizeData(tmp, verbose = FALSE)
    tmp <- Seurat::FindVariableFeatures(tmp, verbose = FALSE)
    tmp <- Seurat::ScaleData(tmp, verbose = FALSE)
    tmp <- Seurat::RunPCA(tmp, verbose = FALSE)
    tmp <- Seurat::FindNeighbors(tmp, dims = dims_use, verbose = FALSE)
    tmp <- Seurat::FindClusters(tmp, resolution = resolution, verbose = FALSE)
    
    sc <- setClusters(sc, tmp$seurat_clusters)
    
    sc  <- autoEstCont(sc)
    out <- adjustCounts(sc)
    
    out.dir <- file.path(base.dir, sid, "outs", out_subdir)
    DropletUtils::write10xCounts(out.dir, out)
    
    if (verbose) {
      rho <- tryCatch(sc$metaData$rho, error = function(e) NULL)
      if (!is.null(rho)) message("  rho summary: ", paste(round(summary(rho), 4), collapse = " | "))
    }
    
    rm(sc, tmp, out)
    gc()
  }
  
  # ---------- 2) Read corrected counts and create Seurat objects ----------
  if (verbose) message("== Step 2/3: Read corrected 10X and create Seurat objects ==")
  
  created <- character(0)
  
  for (sid in sample.names) {
    data.dir <- file.path(base.dir, sid, "outs", out_subdir)
    if (verbose) message("Processing (CreateSeurat): ", sid, " | ", data.dir)
    
    if (!dir.exists(data.dir)) {
      warning("Missing corrected directory: ", data.dir, " (skip ", sid, ")")
      next
    }
    
    counts <- Seurat::Read10X(data.dir = data.dir)
    
    obj <- Seurat::CreateSeuratObject(
      counts       = counts,
      project      = sid,
      min.cells    = min.cells,
      min.features = min.features
    )
    obj$sample <- sid
    
    nm <- paste0(pattern_prefix, sid)
    assign(nm, obj, envir = envir)
    created <- c(created, nm)
    
    rm(obj, counts)
    gc()
  }
  
  if (length(created) == 0) stop("No Seurat objects were created. Check your folders and out_subdir.")
  
  # ---------- 3) Batch QC + clustering + doublet removal ----------
  if (verbose) message("== Step 3/3: BatchProcessSeurat_InPlace (QC + Doublet removal) ==")
  
  BatchProcessSeurat_InPlace(
    obj_names = created,
    mt.genes  = mt.genes,     
    species   = species,      
    sct       = sct,
    verbose   = verbose,
    ...
  )
  
  invisible(list(
    sample.names = sample.names,
    created_objs = created,
    base.dir     = base.dir,
    out_subdir   = out_subdir,
    species      = species
  ))
}
